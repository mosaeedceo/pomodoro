const translations: Record<LanguageCode, Record<string, string>> = { en, ar };

export function getTextDirection(language: LanguageCode): TextDirection {
  return language === "ar" ? "rtl" : "ltr";
}

export function isRtlLanguage(language: LanguageCode): boolean {
  return getTextDirection(language) === "rtl";
}

export function translate(
  language: LanguageCode,
  key: string,
  params: TranslationParams = {},
): string {
  const table = translations[language] ?? translations.en;
  const template = table[key] ?? translations.en[key] ?? key;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function createTranslator(language: LanguageCode) {
  return (key: string, params?: TranslationParams) =>
    translate(language, key, params);
}

